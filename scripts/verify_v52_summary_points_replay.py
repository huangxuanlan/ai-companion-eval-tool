"""
Replay v5.2 mode switching via generated summary + interaction points.

This validates the older switching design where the target-mode request does
not carry raw bridged history. Instead:

- summary: generated by doubao-lite from the source transcript
- interaction points: generated by doubao-lite for short -> long switches
- target reply: target system + one assistant context block + current user

Inputs are production issue-log payloads, not synthetic conversations.
"""
