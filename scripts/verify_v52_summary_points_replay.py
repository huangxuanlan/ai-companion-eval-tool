AUX_MODEL = "doubao-lite"


def extract_time_hint(text: str) -> datetime | None:
    match = re.search(r"(\d{4})年(\d{1,2})月(\d{1,2})日(\d{1,2})[：:](\d{1,2})", text or "")
    if not match:
        return None
    y, m, d, hh, mm = [int(x) for x in match.groups()]
    return datetime(y, m, d, hh, mm)


def transcript_from_messages(messages: list[dict[str, str]], *, base_time: datetime | None = None) -> str:
    base = base_time or datetime(2026, 5, 9, 16, 0)
    lines: list[str] = []
    logical_idx = 0
    for msg in messages:
        if msg["role"] not in {"user", "assistant"}:
            continue
        role = "用户" if msg["role"] == "user" else "角色"
        hint = extract_time_hint(msg.get("content", ""))
        ts = hint or (base + timedelta(minutes=logical_idx * 2))
        logical_idx += 1
        content = msg.get("content", "").strip()
        lines.append(f"[{ts:%m-%d %H:%M}][{role}]\n{content}")
    return "\n\n".join(lines)


def call_model(
    adapter: ModelAdapter,
    model_id: str,
    messages: list[dict[str, str]],
    *,
    max_tokens: int,
    thinking: str = "disabled",
) -> dict[str, Any]:
    started = time.perf_counter()
    result = adapter.chat(
        model_id=model_id,
        messages=messages,
        max_tokens=max_tokens,
        thinking_effort=thinking,
    )
    return {
        "success": result.success,
        "error": result.error,
        "output": result.content or "",
        "latency": round(time.perf_counter() - started, 3),
        "input_tokens": result.input_tokens,
        "output_tokens": result.output_tokens,
    }


def render_summary_prompt(template: str, *, current_mode: str, transcript: str) -> str:
    text = template
    text = text.replace("{current_mode}", current_mode)
    text = text.replace("{existing_summary}", "(首次生成，无旧摘要)")
    text = text.replace("{conversation_log}", transcript)
    return text


def render_points_prompt(template: str, *, transcript: str) -> str:
    return template.replace("{conversation_text}", transcript)


def extract_json_object(text: str) -> tuple[dict[str, Any] | None, str]:
    try:
        return json.loads(text), ""
    except json.JSONDecodeError as first_error:
        match = re.search(r"\{.*\}", text or "", flags=re.S)
        if not match:
            return None, str(first_error)
        try:
            return json.loads(match.group(0)), ""
        except json.JSONDecodeError as second_error:
            return None, str(second_error)


def summary_to_labels(summary: dict[str, Any] | None, target_mode: str) -> str:
    if not summary:
        return ""
    fields = [
        ("scene_description", "【当前场景】"),
        ("plot_summary", "【本次对话智能摘要】"),
    ]
    if target_mode == "long":
        fields.extend(
            [
                ("pending_hooks", "【未兑现的承诺/未完成动作/悬念线索】"),
                ("character_emotion", "【角色情绪】"),
                ("user_emotion", "【用户情绪】"),
                ("relationship_shift", "【关系进展】"),
                ("user_profile_signals", "【用户核心记忆点】"),
            ]
        )
    lines = []
    for key, label in fields:
        value = str(summary.get(key, "") or "").strip()
        if value:
            lines.append(f"{label}{value}")
    return "\n".join(lines)


def build_context_block(
    *,
    summary: dict[str, Any] | None,
    points: str,
    target_mode: str,
) -> str:
    summary_text = summary_to_labels(summary, target_mode)
    parts = [
        "（以下为角色内部认知记录，仅供上下文参考，请勿模仿此格式；这不是角色实际回复。仅为已发生事实，不是当前场景指令；若与当前输入冲突，以当前输入为准。）"
    ]
    if summary_text:
        parts.append(summary_text)
    if points.strip():
        parts.append(points.strip())
    parts.append("=== 摘要结束 ===")
    parts.append("（内部认知记录结束。以下对话才是真实聊天。）")
    return "\n".join(parts)


def source_for_scenario(
    scenario: str,
    short_sample: LogSample,
    long_sample: LogSample,
) -> tuple[str, str, list[dict[str, str]], dict[str, str], dict[str, str], bool]:
    short_hist = dialogue_history(short_sample)
    long_hist = dialogue_history(long_sample)
    if scenario == "S5":
        return "long", "deepseek-v4-pro", short_hist[-40:], first_system(long_sample.messages), last_user(long_sample.messages), True
    if scenario == "S6":
        return "short", "doubao-lite", long_hist[-20:], first_system(short_sample.messages), last_user(short_sample.messages), False
    if scenario == "S8":
        mixed = short_hist + long_hist
        return "short", "doubao-lite", mixed[-20:], first_system(short_sample.messages), last_user(short_sample.messages), False
    if scenario == "S14":
        mixed = short_hist + long_hist
        return "long", "deepseek-v4-pro", mixed[-40:], first_system(long_sample.messages), last_user(long_sample.messages), True
    raise ValueError(f"未知场景: {scenario}")


def evaluate_output(output: str, messages: list[dict[str, str]], target_mode: str) -> dict[str, Any]:
    assistants = recent_assistant_texts(messages, limit=8)
    overlaps = [ngram_overlap(prev, output) for prev in assistants]
    last_assistant = assistants[-1] if assistants else ""
    return {
        "chars": len(output),
        "cjk_chars": cjk_len(output),
        "format_issues": detect_format_issues(output, target_mode),
        "ngram_last_pct": round(ngram_overlap(last_assistant, output) * 100, 2),
        "ngram_max_recent_pct": round((max(overlaps) if overlaps else 0.0) * 100, 2),
        "output_preview": output[:500],
    }


def append_jsonl(path: Path, item: dict[str, Any]) -> None:
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(item, ensure_ascii=False) + "\n")


def write_summary(results: list[dict[str, Any]], path: Path) -> None:
    lines = [
        "# v5.2 摘要+互动要点切换复放验证报告",
        "",
        f"- 生成时间: {datetime.now().isoformat()}",
        "- 输入来源: 问题排查目录中的真实 payload 日志",
        "- 切换方式: 不带原始桥接历史；只注入 generated summary / interaction points",
        f"- 辅助模型: {AUX_MODEL}",
        "",
        "| 场景 | 目标 | 摘要输入轮数 | 互动要点 | payload消息 | 摘要JSON | 成功 | 字数 | 格式问题 | recent-max-ngram |",
        "|:--|:--|--:|:--:|--:|:--:|:--:|--:|:--|--:|",
    ]
    for r in results:
        issues = "；".join(r["metrics"].get("format_issues") or []) or "无"
        lines.append(
            "| {scenario} | {target_mode}/{target_model} | {source_turns} | {points} | {payload_messages} | "
            "{summary_json} | {success} | {chars} | {issues} | {ngram} |".format(
                scenario=r["scenario"],
                target_mode=r["target_mode"],
                target_model=r["target_model"],
                source_turns=r["source_effective_turns"],
                points="Y" if r["points_generated"] else "N",
                payload_messages=r["payload_messages"],
                summary_json="Y" if r["summary_json_ok"] else "N",
                success="Y" if r["success"] else "N",
                chars=r["metrics"].get("cjk_chars", 0),
                issues=issues,
                ngram=r["metrics"].get("ngram_max_recent_pct", 0),
            )
        )
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Validate v5.2 summary + interaction-points switching")
    parser.add_argument("--short-log", default=str(SHORT_LOG_DEFAULT))
    parser.add_argument("--long-log", default=str(LONG_LOG_DEFAULT))
    parser.add_argument("--summary-prompt", default=str(SUMMARY_PROMPT_DEFAULT))
    parser.add_argument("--points-prompt", default=str(POINTS_PROMPT_DEFAULT))
    parser.add_argument("--scenarios", nargs="*", default=["S5", "S6", "S8", "S14"])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--output-dir", default="")
    args = parser.parse_args()

    short_sample = load_log_sample(Path(args.short_log), mode="short")
    long_sample = load_log_sample(Path(args.long_log), mode="long")
    summary_template = Path(args.summary_prompt).read_text(encoding="utf-8", errors="ignore")
    points_template = Path(args.points_prompt).read_text(encoding="utf-8", errors="ignore")

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    out_dir = Path(args.output_dir) if args.output_dir else PROJECT_ROOT / "output" / "v52_summary_points_replay" / ts
    payload_dir = out_dir / "payloads"
    aux_dir = out_dir / "auxiliary"
    payload_dir.mkdir(parents=True, exist_ok=True)
    aux_dir.mkdir(parents=True, exist_ok=True)
    results_path = out_dir / "results.jsonl"
    summary_path = out_dir / "summary.md"

    adapter = ModelAdapter()
    results: list[dict[str, Any]] = []
    print(f"[INFO] short_log={short_sample.path} messages={len(short_sample.messages)}")
    print(f"[INFO] long_log={long_sample.path} messages={len(long_sample.messages)}")
    print(f"[INFO] summary_prompt={args.summary_prompt}")
    print(f"[INFO] points_prompt={args.points_prompt}")
    print(f"[INFO] output={out_dir}")

    for scenario in args.scenarios:
        target_mode, target_model, source_messages, system_msg, current_user, needs_points = source_for_scenario(
            scenario,
            short_sample,
            long_sample,
        )
        transcript = transcript_from_messages(source_messages, base_time=extract_time_hint(current_user["content"]))
        source_turns = len([m for m in source_messages if m["role"] in {"user", "assistant"}]) // 2
        current_mode = "longform" if target_mode == "long" else "shortform"

        summary_prompt = render_summary_prompt(summary_template, current_mode=current_mode, transcript=transcript)
        points_prompt = render_points_prompt(points_template, transcript=transcript)

        if args.dry_run:
            summary_call = {
                "success": True,
                "error": "",
                "output": '{"scene_description":"dry-run场景","plot_summary":"[05-09 16:00]dry-run摘要","pending_hooks":"","character_emotion":"","user_emotion":"","relationship_shift":"","user_profile_signals":""}',
                "latency": 0.0,
                "input_tokens": 0,
                "output_tokens": 0,
            }
            points_call = {
                "success": True,
                "error": "",
                "output": "【最近互动要点（桥接迁移）】\n1. [05-09 16:00] dry-run互动要点\n【待接续线索】\n【最后场景】",
                "latency": 0.0,
                "input_tokens": 0,
                "output_tokens": 0,
            } if needs_points else {"success": True, "error": "", "output": "", "latency": 0.0, "input_tokens": 0, "output_tokens": 0}
        else:
            summary_call = call_model(
                adapter,
                AUX_MODEL,
                [{"role": "user", "content": summary_prompt}],
                max_tokens=1200,
                thinking="disabled",
            )
            points_call = (
                call_model(
                    adapter,
                    AUX_MODEL,
                    [{"role": "user", "content": points_prompt}],
                    max_tokens=900,
                    thinking="disabled",
                )
                if needs_points
                else {"success": True, "error": "", "output": "", "latency": 0.0, "input_tokens": 0, "output_tokens": 0}
            )

        summary_json, summary_json_error = extract_json_object(summary_call["output"])
        context_block = build_context_block(
            summary=summary_json,
            points=points_call["output"],
            target_mode=target_mode,
        )
        messages = [
            system_msg,
            {"role": "assistant", "content": context_block},
            current_user,
        ]
        case_id = f"{scenario}_v52_summary_points"
        (aux_dir / f"{case_id}_transcript.txt").write_text(transcript, encoding="utf-8")
        (aux_dir / f"{case_id}_summary_prompt.txt").write_text(summary_prompt, encoding="utf-8")
        (aux_dir / f"{case_id}_summary_output.txt").write_text(summary_call["output"], encoding="utf-8")
        (aux_dir / f"{case_id}_points_prompt.txt").write_text(points_prompt if needs_points else "", encoding="utf-8")
        (aux_dir / f"{case_id}_points_output.txt").write_text(points_call["output"], encoding="utf-8")
        payload_path = payload_dir / f"{case_id}.json"
        payload_path.write_text(
            json.dumps(
                {
                    "meta": {
                        "scenario": scenario,
                        "target_mode": target_mode,
                        "target_model": target_model,
                        "source_effective_turns": source_turns,
                        "summary_prompt": str(args.summary_prompt),
                        "points_prompt": str(args.points_prompt),
                    },
                    "messages": messages,
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )

        print(
            f"[RUN] {case_id} target={target_mode}/{target_model} "
            f"source_turns={source_turns} points={needs_points}"
        )
        if args.dry_run:
            target_call = {
                "success": True,
                "error": "",
                "output": "（dry-run 占位旁白。）（用于验证 v5.2 摘要与互动要点 payload。）（不会调用目标模型。）",
                "latency": 0.0,
                "input_tokens": 0,
                "output_tokens": 0,
            }
        else:
            target_call = call_model(
                adapter,
                target_model,
                messages,
                max_tokens=16384 if target_mode == "long" else 4096,
                thinking="high" if target_mode == "long" else "disabled",
            )

        metrics = evaluate_output(target_call["output"], messages, target_mode)
        record = {
            "case_id": case_id,
            "scenario": scenario,
            "target_mode": target_mode,
            "target_model": target_model,
            "source_effective_turns": source_turns,
            "source_messages": len(source_messages),
            "summary_model": AUX_MODEL,
            "points_model": AUX_MODEL if needs_points else "",
            "summary_success": summary_call["success"],
            "summary_error": summary_call["error"],
            "summary_latency": summary_call["latency"],
            "summary_input_tokens": summary_call["input_tokens"],
            "summary_output_tokens": summary_call["output_tokens"],
            "summary_json_ok": summary_json is not None,
            "summary_json_error": summary_json_error,
            "summary_output": summary_call["output"],
            "points_generated": needs_points,
            "points_success": points_call["success"],
            "points_error": points_call["error"],
            "points_latency": points_call["latency"],
            "points_input_tokens": points_call["input_tokens"],
            "points_output_tokens": points_call["output_tokens"],
            "points_output": points_call["output"],
            "payload_path": str(payload_path),
            "payload_messages": len(messages),
            **{k: v for k, v in target_call.items() if k != "output"},
            "metrics": metrics,
            "output": target_call["output"],
        }
        append_jsonl(results_path, record)
        results.append(record)
        write_summary(results, summary_path)
        print(
            f"[OK] {case_id} success={record['success']} summary_json={record['summary_json_ok']} "
            f"chars={metrics['cjk_chars']} issues={len(metrics['format_issues'])} "
            f"max_ngram={metrics['ngram_max_recent_pct']}"
        )

    print(f"[DONE] results={results_path}")
    print(f"[DONE] summary={summary_path}")


if __name__ == "__main__":
    main()
